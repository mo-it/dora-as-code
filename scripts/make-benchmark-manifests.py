#!/usr/bin/env python3
"""
make-benchmark-manifests.py — build the zero-replica benchmark manifest set.

THE PROBLEM THIS SOLVES
-----------------------
The Phase 4 sync benchmark measured 197-214 seconds per cycle, and the baseline
configuration (no policy engine running at all) was just as slow as the treatment
configurations. That is the giveaway: the measurement was not capturing admission
overhead.

manifests/compliant/ contains 21 Deployments, each scheduling a real nginx pod.
On a single-node 8GB cluster, `argocd app sync` therefore waits on ~22 pods to be
scheduled and their images pulled. Container lifecycle dominated the timing and
buried the policy engine signal entirely. It also starved the node badly enough
that Kyverno could not finish re-registering its webhooks within 150 seconds.

THE FIX
-------
Set `replicas: 0`. The Deployment object still traverses the admission chain in
full -- every policy evaluates against it exactly as before -- but no pod is
created, so the sync completes as soon as the API server has accepted the object.

Café analogy: to time the health inspector you send the paperwork through, not a
lorry-load of stock. The inspection is identical; you just aren't waiting for the
delivery to be unloaded afterwards.

EXCEPTIONS
----------
REQ-007 (minimum replicas) and REQ-024 (PodDisruptionBudget) apply only to
workloads labelled criticality=high, and REQ-007 requires replicas >= 2. Setting
those to zero would make a compliant manifest non-compliant, so they are excluded
from the benchmark set rather than modified. Excluding two of 21 manifests does
not affect a latency measurement, and the alternative -- silently weakening a
compliant fixture -- would be worse.

USAGE
    python3 scripts/make-benchmark-manifests.py
    python3 scripts/make-benchmark-manifests.py --dry-run

Then point the benchmark ArgoCD Application at manifests/benchmark/.
"""

import argparse
import os
import shutil
import sys

import yaml

# Excluded: their compliant form requires replicas >= 2 (criticality=high).
EXCLUDE = {"req007", "req024"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="manifests/compliant")
    ap.add_argument("--out", default="manifests/benchmark")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if not os.path.isdir(args.src):
        sys.exit(f"ERROR: source directory not found: {args.src}")

    if not args.dry_run:
        shutil.rmtree(args.out, ignore_errors=True)
        os.makedirs(args.out, exist_ok=True)

    kept = skipped = zeroed = 0
    print(f"{'FILE':34s} {'KIND':26s} ACTION")
    print("-" * 78)

    for fname in sorted(os.listdir(args.src)):
        if not fname.endswith((".yaml", ".yml")):
            continue
        req = fname.split("-")[0]
        path = os.path.join(args.src, fname)

        with open(path) as fh:
            doc = yaml.safe_load(fh)
        if not doc:
            continue
        kind = doc.get("kind", "?")

        if req in EXCLUDE:
            print(f"{fname:34s} {kind:26s} SKIP (needs replicas>=2)")
            skipped += 1
            continue

        action = "copied"
        if kind in ("Deployment", "StatefulSet") and "replicas" in doc.get("spec", {}):
            doc["spec"]["replicas"] = 0
            action = "replicas -> 0"
            zeroed += 1

        print(f"{fname:34s} {kind:26s} {action}")
        kept += 1

        if not args.dry_run:
            with open(os.path.join(args.out, fname), "w") as fh:
                fh.write("# AUTO-GENERATED by scripts/make-benchmark-manifests.py\n"
                         "# replicas set to 0: the object still traverses the full\n"
                         "# admission chain, but schedules no pod, so sync timing\n"
                         "# measures admission rather than container lifecycle.\n")
                yaml.safe_dump(doc, fh, sort_keys=False, default_flow_style=False)

    print()
    print(f"Included: {kept}   Zero-replica: {zeroed}   Excluded: {skipped}")
    if not args.dry_run:
        print(f"Written to: {args.out}/")
        print("\nNext: point the benchmark Application at this path, then")
        print("  kubectl apply -f argocd/application-benchmark.yaml")


if __name__ == "__main__":
    main()
